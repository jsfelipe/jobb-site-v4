export function shuffleProvisionMessages(): string[] {
  const list = [...PROVISION_WAITING_MESSAGES];
  for (let i = list.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    const tmp = list[i];
    list[i] = list[j];
    list[j] = tmp;
  }
  return list;
}
